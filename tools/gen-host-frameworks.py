#!/usr/bin/env python3
"""Generate PearHost's additional frameworks from census reports.

An iOS app links frameworks macOS does not have (MessageUI, EventKitUI, iAd,
...) or that macOS has without some iOS-only API (AVKit's
AVPlayerViewController, GameController's GCVirtualController, ...). dyld
refuses to start the app unless every non-weak import resolves, so PearHost
ships a framework of the same name for each:

  stub     the framework does not exist on macOS: our image is all of it
  overlay  macOS has it: our image re-exports the system framework and adds
           what the app imports that macOS lacks

Each generated image defines the imported classes (empty, with the public
superclass, so every message reaches the missing-call reporter), C function
stubs that report themselves and return zero, and data constants typed from
the public headers. tools/host-prepare.sh and the launcher redirect an app's
load commands to every framework build-host.sh produced.

Outputs, in rust/crates/pear-host-frameworks:
  src/generated/<name>.rs   one module per framework (selected at build time)
  frameworks.txt            "<name> stub|overlay" per line, for build-host.sh

Inputs are interface-only: census JSON (from the app's own binaries), the
public SDK headers, and which names the macOS frameworks export (dlsym /
objc class lookup of public symbols; no code is read).

  tools/gen-host-frameworks.py docs/census/*.json
"""
import ctypes
import glob
import importlib.util
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRATE = os.path.join(ROOT, "rust/crates/pear-host-frameworks")
OUT = os.path.join(CRATE, "src/generated")

spec = importlib.util.spec_from_file_location("uikit_stubs", os.path.join(ROOT, "tools/gen-uikit-stubs.py"))
uikit_stubs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(uikit_stubs)

# Frameworks implemented elsewhere in PearHost (pear-uikit, pear-gles,
# pear-metalkit) or mapped to another macOS framework by the preparers.
HANDLED = {"UIKit", "OpenGLES", "MetalKit", "GLKit", "MobileCoreServices",
           # Swift metadata and witness tables, which plain stubs cannot stand
           # in for (UIViewRepresentable & co.).
           "SwiftUI"}
# iOS-only frameworks apps link without importing anything from them (no
# census entry); they still need an image to exist.
ALWAYS_STUB = {"iAd", "MessageUI", "EventKitUI", "AssetsLibrary", "AddressBookUI", "Twitter"}
# Superclasses of classes whose framework headers the SDK does not carry.
KNOWN_SUPERCLASSES = {"GLKView": "UIView", "GLKViewController": "UIViewController"}


def sdk_path():
    return subprocess.check_output(["xcrun", "--sdk", "macosx", "--show-sdk-path"], text=True).strip()


def ios_headers(sdk, framework):
    text = {}
    for hd in glob.glob(os.path.join(sdk, f"System/iOSSupport/System/Library/Frameworks/{framework}.framework/Headers")):
        for f in sorted(os.listdir(hd)):
            if f.endswith(".h"):
                text[f] = open(os.path.join(hd, f), errors="ignore").read()
    return text


class MacOS:
    """What the macOS frameworks export, by public symbol lookup."""

    def __init__(self, sdk):
        self.sdk = sdk
        self.libc = ctypes.CDLL(None)
        self.libc.dlopen.restype, self.libc.dlopen.argtypes = ctypes.c_void_p, [ctypes.c_char_p, ctypes.c_int]
        self.libc.dlsym.restype, self.libc.dlsym.argtypes = ctypes.c_void_p, [ctypes.c_void_p, ctypes.c_char_p]
        self.handles = {}

    def has_framework(self, name):
        return os.path.isdir(os.path.join(self.sdk, f"System/Library/Frameworks/{name}.framework"))

    def handle(self, name):
        if name not in self.handles:
            path = f"/System/Library/Frameworks/{name}.framework/{name}"
            self.handles[name] = self.libc.dlopen(path.encode(), 1)
        return self.handles[name]

    def exports(self, framework, symbol):
        h = self.handle(framework)
        return bool(h and self.libc.dlsym(h, symbol.encode()))


def rust_ident(name):
    return re.sub(r"\W", "_", name)


def generate(name, kind, classes, symbols, sup, decls):
    """Rust module for one framework."""
    m = [f"// GENERATED by tools/gen-host-frameworks.py from census reports and public",
         f"// headers: PearHost {name}.framework ({kind}). Do not edit; regenerate.",
         "",
         "use std::ffi::c_void;", "", "pear_objc::image_info!();", ""]
    # Parents before children; superclasses outside this image are linked
    # from PearHost UIKit (UI*) or the system (NS*, anything else).
    order = []

    def visit(c):
        if c in order or c not in classes:
            return
        visit(sup.get(c, "NSObject"))
        order.append(c)

    for c in sorted(classes):
        visit(c)
    external = sorted({sup.get(c, "NSObject") for c in order if sup.get(c, "NSObject") not in classes} | {"NSObject"})
    m.append('extern "C" {')
    for s in external:
        m += [f'    #[link_name = "OBJC_CLASS_$_{s}"]', f"    static {s}_CLASS: c_void;",
              f'    #[link_name = "OBJC_METACLASS_$_{s}"]', f"    static {s}_META: c_void;"]
    m += ["    fn PearMissingInstallForImage(address_in_image: *const c_void);", "}", ""]
    for c in order:
        s = sup.get(c, "NSObject")
        if s in classes:
            m.append(f"pear_objc::empty_class!({c} : super::{s}::CLASS.ptr(), super::{s}::META.ptr());")
        else:
            m.append(f"pear_objc::empty_class!({c} : &raw const super::{s}_CLASS, &raw const super::{s}_META);")
    placeholders, funcs = [], []
    for sym in sorted(symbols):
        line = uikit_stubs.data_constant(sym, decls, placeholders)
        if line is None:
            funcs.append(sym)
        else:
            m.append(line)
    if funcs:
        m += uikit_stubs.function_stubs(funcs, f"pear_{rust_ident(name)}")
    m += ["",
          "/// Image initializer: every message to these classes reaches the",
          "/// missing-call reporter (PearHost UIKit) instead of raising.",
          'extern "C" fn pear_host_framework_load() {',
          "    unsafe { PearMissingInstallForImage(pear_host_framework_load as *const c_void) };",
          "}", "",
          "#[used]",
          '#[link_section = "__DATA,__mod_init_func,mod_init_funcs"]',
          'static PEAR_HOST_FRAMEWORK_INIT: extern "C" fn() = pear_host_framework_load;']
    return "\n".join(m) + "\n", placeholders, funcs


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    sdk = sdk_path()
    macos = MacOS(sdk)
    want_classes, want_syms = {}, {}
    for p in argv[1:]:
        for lib, v in json.load(open(p))["libraries"].items():
            if lib.startswith(("<", "lib")) or lib in HANDLED:
                continue
            want_classes.setdefault(lib, set()).update(v["classes"])
            want_syms.setdefault(lib, set()).update(s[1:] if s.startswith("_") else s for s in v["symbols"])
    for lib in ALWAYS_STUB:
        want_classes.setdefault(lib, set())
        want_syms.setdefault(lib, set())

    frameworks = []
    os.makedirs(OUT, exist_ok=True)
    for old in glob.glob(os.path.join(OUT, "*.rs")):
        os.remove(old)
    for lib in sorted(want_classes):
        if macos.has_framework(lib):
            kind = "overlay"
            classes = {c for c in want_classes[lib] if not macos.exports(lib, f"OBJC_CLASS_$_{c}")}
            symbols = {s for s in want_syms[lib] if not macos.exports(lib, s)}
            if not classes and not symbols:
                continue
        else:
            kind = "stub"
            classes, symbols = want_classes[lib], want_syms[lib]
        headers = ios_headers(sdk, lib)
        sup = {**uikit_stubs.superclasses(headers), **KNOWN_SUPERCLASSES}
        # Close over superclasses this framework itself defines.
        todo = list(classes)
        while todo:
            c = todo.pop()
            s = sup.get(c, "NSObject")
            if s not in classes and s in sup and not s.startswith(("NS", "UI")) \
                    and not (macos.has_framework(lib) and macos.exports(lib, f"OBJC_CLASS_$_{s}")):
                classes.add(s)
                todo.append(s)
        decls = uikit_stubs.extern_decls(headers)
        source, placeholders, funcs = generate(lib, kind, classes, symbols, sup, decls)
        with open(os.path.join(OUT, f"{lib}.rs"), "w") as f:
            f.write(source)
        frameworks.append((lib, kind))
        print(f"{lib:16} {kind:8} classes: {' '.join(sorted(classes)) or '-'}")
        if symbols:
            print(f"{'':25} symbols: {len(symbols)} ({len(funcs)} function stubs, {len(placeholders)} placeholders)")
    with open(os.path.join(CRATE, "frameworks.txt"), "w") as f:
        f.write("# GENERATED by tools/gen-host-frameworks.py: <framework> stub|overlay\n")
        for lib, kind in frameworks:
            f.write(f"{lib} {kind}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
